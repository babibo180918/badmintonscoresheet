/* t('en', 'ui.undo') or t('en', 'call.firstGameWonBy', {name: 'X'}) */
function t(lang, path, vars) {
  let node = I18N[lang] || I18N.en;
  for (const p of path.split(".")) node = node[p];
  if (typeof node === "string" && vars) {
    return node.replace(/\{(\w+)\}/g, (_, k) => vars[k]);
  }
  return node;
}
